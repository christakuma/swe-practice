"""`node-modules-vanished`: the ticket, every counter-example, every right answer.

Each case brings a stack up under its own project name and takes it down with
its volumes, as `test_compose_diagnoses.py` does, so a volume filled by one
case cannot be handed to the next. That would hide the very behaviour the
exercise is about: a volume is filled from the image only while it is empty.

The published port is dropped and the service is asked from inside, with
Node's own `fetch`, so a run never collides with something on host port 3000.
"""

from __future__ import annotations

import subprocess
import time
import uuid
from typing import TYPE_CHECKING

import pytest
import yaml

from tests.content.test_container_answers import ANSWERS, MODULES
from tests.docker.conftest import LABEL, docker, exercise

if TYPE_CHECKING:
    from collections.abc import Callable, Iterator
    from pathlib import Path

EXERCISE = exercise(MODULES)

_FETCH = (
    "fetch('http://127.0.0.1:3000/healthz')"
    ".then(r => r.text()).then(t => process.stdout.write(t))"
)


class Stack:
    def __init__(self, workspace: Path) -> None:
        self.workspace = workspace
        self.project = f"swe-practice-test-{uuid.uuid4().hex[:8]}"

    def compose(
        self, *args: str, timeout: float = 300
    ) -> subprocess.CompletedProcess[str]:
        return subprocess.run(  # noqa: S603
            ["docker", "compose", "-p", self.project, *args],  # noqa: S607
            cwd=self.workspace, capture_output=True, text=True,
            timeout=timeout, check=False,
        )  # fmt: skip

    def up(self, *extra: str) -> subprocess.CompletedProcess[str]:
        return self.compose("up", "-d", "--build", "--quiet-pull", *extra)

    def logs(self) -> str:
        return self.compose("logs", "--no-color", "web").stdout

    def run_in(self, *command: str) -> subprocess.CompletedProcess[str]:
        return self.compose("exec", "-T", "web", *command)

    def serves(self, seconds: float = 20) -> bool:
        deadline = time.monotonic() + seconds
        while time.monotonic() < deadline:
            if self.run_in("node", "-e", _FETCH).stdout == "ok\n":
                return True
            time.sleep(1)
        return False

    def image_modules(self) -> list[str]:
        """`node_modules` in the built image, without the compose file's mounts."""
        image = f"{self.project}-web"
        listing = docker(
            "run", "--rm", "--label", LABEL, image, "ls", "/app/node_modules"
        )
        return listing.split()

    def down(self) -> None:
        self.compose("down", "-v", "--remove-orphans", timeout=120)


type MakeStack = Callable[[str], Stack]


@pytest.fixture
def stack(tmp_path: Path) -> Iterator[MakeStack]:
    made: list[Stack] = []

    def make(answer: str) -> Stack:
        workspace = EXERCISE.workspace(tmp_path, "compose.yaml")
        compose = workspace / "compose.yaml"
        text = (
            ANSWERS[answer][1]
            if answer in ANSWERS
            else (EXERCISE.directory / answer).read_text(encoding="utf-8")
        )
        document = yaml.safe_load(text)
        document["services"]["web"].pop("ports", None)
        compose.write_text(yaml.safe_dump(document), encoding="utf-8")
        created = Stack(workspace)
        made.append(created)
        return created

    yield make
    for created in made:
        created.down()


# --- the ticket --------------------------------------------------------------


def test_the_bind_mount_hides_the_images_modules(stack: MakeStack) -> None:
    running = stack("compose.yaml")
    assert running.up().returncode == 0
    time.sleep(5)
    assert "Error: Cannot find module 'polka'" in running.logs()
    assert "Waiting for file changes before restarting" in running.logs()
    assert running.run_in("ls", "/app/node_modules").returncode != 0
    assert "polka" in running.image_modules()


def test_the_reference_serves_the_images_modules(stack: MakeStack) -> None:
    running = stack("solution.compose.yaml")
    assert running.up().returncode == 0
    assert running.serves(), running.logs()
    # The anonymous volume leaves an empty mount point in the checkout.
    assert list((running.workspace / "node_modules").iterdir()) == []


def test_the_volume_outlives_a_recreate_until_it_is_renewed(stack: MakeStack) -> None:
    """The notes' catch: an anonymous volume is only filled while it is empty."""
    running = stack("solution.compose.yaml")
    assert running.up().returncode == 0
    assert running.run_in("touch", "/app/node_modules/MARKER").returncode == 0
    assert running.up("--force-recreate").returncode == 0
    assert "MARKER" in running.run_in("ls", "/app/node_modules").stdout
    assert running.up("--force-recreate", "-V").returncode == 0
    assert "MARKER" not in running.run_in("ls", "/app/node_modules").stdout


# --- the counter-examples ----------------------------------------------------


def test_without_the_bind_an_edit_does_not_reach_the_container(
    stack: MakeStack,
) -> None:
    running = stack("drop-the-bind-mount.compose.yaml")
    assert running.up().returncode == 0
    assert running.serves(), running.logs()
    server = running.workspace / "server.js"
    server.write_text(
        server.read_text(encoding="utf-8") + "// edited on the host\n",
        encoding="utf-8",
        newline="\n",
    )
    assert "edited on the host" not in running.run_in("cat", "/app/server.js").stdout


def test_a_bind_at_node_modules_shows_the_hosts_empty_one(stack: MakeStack) -> None:
    running = stack("bind-node-modules-too.compose.yaml")
    assert running.up().returncode == 0
    time.sleep(5)
    assert "Error: Cannot find module 'polka'" in running.logs()
    assert list((running.workspace / "node_modules").iterdir()) == []


def test_installing_on_start_writes_into_the_checkout(stack: MakeStack) -> None:
    running = stack("install-on-start.compose.yaml")
    assert running.up().returncode == 0
    assert running.serves(60), running.logs()
    assert "added 5 packages" in running.logs()
    assert (running.workspace / "node_modules" / "polka").is_dir()


# --- the answers the prompt does not rule out --------------------------------


@pytest.mark.parametrize(
    "name", sorted(name for name, (slug, _, _) in ANSWERS.items() if slug == MODULES)
)
def test_every_accepted_answer_serves(stack: MakeStack, name: str) -> None:
    running = stack(name)
    result = running.up()
    assert result.returncode == 0, result.stderr
    assert running.serves(), running.logs()


def test_an_undeclared_named_volume_is_refused(stack: MakeStack) -> None:
    running = stack("named-volume")
    compose = running.workspace / "compose.yaml"
    document = yaml.safe_load(compose.read_text(encoding="utf-8"))
    del document["volumes"]
    compose.write_text(yaml.safe_dump(document), encoding="utf-8")
    result = running.up()
    assert result.returncode != 0
    assert 'service "web" refers to undefined volume node_modules' in result.stderr
