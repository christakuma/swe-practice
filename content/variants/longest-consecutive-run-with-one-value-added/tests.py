"""The hidden test suite.

Each test's docstring becomes the label on its `CheckReport`.
"""

from itertools import combinations

from solution import longest_run


def by_trying_every_value(numbers: list[int]) -> int:
    """The answer by adding each candidate in turn and measuring. An oracle.

    A value further than one from everything present makes a run of one, so
    the candidates worth trying are those from one below the smallest to one
    above the largest.
    """
    if not numbers:
        return 1
    best = 0
    for added in range(min(numbers) - 1, max(numbers) + 2):
        values = sorted({*numbers, added})
        length = 1
        for position, value in enumerate(values):
            length = length + 1 if position and value == values[position - 1] + 1 else 1
            best = max(best, length)
    return best


def test_fills_a_gap_between_two_runs() -> None:
    """Joins two runs separated by one missing value."""
    assert longest_run([1, 2, 4, 5]) == 5


def test_extends_a_run_when_there_is_no_gap_to_fill() -> None:
    """Returns one more than the longest run when nothing can be joined."""
    assert longest_run([1, 2, 3]) == 4
    assert longest_run([10, 4, 20, 1, 3, 2]) == 5


def test_an_empty_list_gives_a_run_of_one() -> None:
    """Returns 1 for no values: the one added."""
    assert longest_run([]) == 1


def test_a_single_value_gives_a_run_of_two() -> None:
    """Returns 2 for one value, with the added value beside it."""
    assert longest_run([7]) == 2


def test_fills_only_one_gap() -> None:
    """Joins two runs and not three when there are two gaps."""
    assert longest_run([1, 3, 5]) == 3
    assert longest_run([1, 2, 4, 5, 7, 8]) == 5


def test_a_gap_of_two_cannot_be_filled() -> None:
    """Does not join runs that are two missing values apart."""
    assert longest_run([1, 2, 5, 6]) == 3


def test_joining_two_short_runs_can_beat_extending_a_long_one() -> None:
    """Chooses the gap when the joined runs are longer than the longest run plus one."""
    assert longest_run([1, 2, 3, 4, 20, 21, 22, 24, 25, 26]) == 7


def test_extending_a_long_run_can_beat_joining_two_short_ones() -> None:
    """Chooses to extend when no join is as long."""
    assert longest_run([1, 2, 3, 4, 5, 6, 20, 22]) == 7


def test_picks_the_better_of_the_gaps_on_either_side_of_a_run() -> None:
    """Joins a run to its longer neighbour.

    The middle run 10, 11 has a run of one below its lower gap and a run of
    four above its upper one.
    """
    assert longest_run([8, 10, 11, 13, 14, 15, 16]) == 7
    assert longest_run([5, 6, 7, 8, 10, 11, 13]) == 7


def test_duplicates_do_not_lengthen_a_run() -> None:
    """Counts each value once however often it appears."""
    assert longest_run([1, 2, 2, 3]) == 4
    assert longest_run([4, 4, 4]) == 2
    assert longest_run([1, 1, 3, 3]) == 3


def test_handles_negative_values_and_runs_across_zero() -> None:
    """Joins runs on either side of zero."""
    assert longest_run([-2, -1, 1, 2]) == 5
    assert longest_run([-5, -3]) == 3


def test_order_does_not_matter() -> None:
    """Returns the same answer however the values are arranged."""
    assert longest_run([5, 1, 4, 2]) == 5
    assert longest_run([9, 7, 3, 1, 8, 2]) == 4


def test_agrees_with_trying_every_value_on_every_small_set() -> None:
    """Matches adding each candidate in turn, for every subset of ten values.

    Every subset of 0..9, which is every arrangement of runs and gaps that
    fits in ten places.
    """
    for size in range(11):
        for chosen in combinations(range(10), size):
            numbers = list(chosen)
            assert longest_run(numbers) == by_trying_every_value(numbers), numbers


def test_agrees_with_trying_every_value_on_lists_with_repeats() -> None:
    """Matches the same check on jumbled lists that repeat their values.

    Three hundred lists of up to a dozen values between -6 and 6, in no
    order, generated by arithmetic so that they are the same every run.
    """
    for seed in range(300):
        numbers = [
            (seed * 7 + step * step * 5 + step) % 13 - 6
            for step in range(1 + seed % 12)
        ]

        assert longest_run(numbers) == by_trying_every_value(numbers), numbers


def test_joins_two_long_runs_in_linear_time() -> None:
    """Joins two runs of a hundred thousand values each.

    One run of two hundred thousand and one with its middle value missing
    are the worst case for a solution that starts a walk from every value
    and not only from the bottom of each run.
    """
    half = 100_000
    ordered = [*range(half), *range(half + 1, 2 * half + 1)]
    numbers = [
        ordered[position * 7_919 % len(ordered)] for position in range(len(ordered))
    ]

    assert sorted(numbers) == ordered
    assert longest_run(numbers) == 2 * half + 1


def test_handles_values_that_are_far_apart() -> None:
    """Returns 2 when no two values are within two of each other."""
    numbers = list(range(-(10**9), 10**9, 10_000))

    assert longest_run(numbers) == 2
