"""A tutor context as text: the Markdown you paste, and the JSON a script reads.

Pure functions over a `TutorContext`, and the last step of Phase 18. Nothing
here decides what a tutor may be told -- `ExportTutorContext` did that, by
building a context with the answer left out -- so these two can render every
field they are handed without an opinion about any of them. That is the point
of splitting the job in two: the half that has to be right about spoilers has
no formatting in it, and the half with all the formatting in it cannot leak.

**In `application/` rather than in an interface module, and `graph.py` already
made the argument.** Three driving adapters hand this text to someone -- the
workbench's copy button, `practice context` and the MCP server -- and a
rendering owned by any one of them would be imported by the other two, sideways
across the interface layer. It is a view model with no I/O in it, which is the
application layer's business, and living here puts it inside the coverage gate.

**Markdown is the default and JSON is the alternative, which is the reverse of
where this started.** The first sketch was "a JSON file that tracks what I did".
But the reader is a chat model by way of a person's clipboard, and both of them
read prose with fenced blocks more easily than nested quoting: a conflicted
file's contents inside a JSON string is a wall of `\\n`. JSON stays for the
caller that wants to do something with the fields, and both are built from the
same context so they cannot disagree about what happened.

**Written in the first person.** The solver is the one pasting it, so "what I
have done so far" reads as their message, and the prompt above it is addressed
to the model. A bundle that narrated the solver in the third person would make
the model's first reply talk past the person who sent it.

**Every fence is sized to its contents.** A command's output can contain a
Markdown fence -- `git show` on a README does -- and three backticks around
text holding three backticks ends the block early and turns the rest of the
transcript into prose. `_fenced` uses one more backtick than the longest run
inside, which is the rule CommonMark gives for exactly this.

`TUTOR_PROMPT` is here rather than in a template or a content file because it
is behaviour: it is the instruction that makes the difference between a tutor
and an answer key, all three surfaces must send the same one, and it is short
enough to read in the place it is used.
"""

from __future__ import annotations

import re
from typing import TYPE_CHECKING, Final

from practice.application.dto import short_ref
from practice.domain.attempt import CommandRun
from practice.domain.exercise import ExerciseKind

if TYPE_CHECKING:
    from collections.abc import Mapping

    from practice.application.dto import RepoView, TutorContext
    from practice.application.graph import GraphRow
    from practice.domain.attempt import HintRevealed
    from practice.domain.ids import Sha
    from practice.domain.ports import WorktreeStatus
    from practice.domain.verdict import CheckReport, Verdict

__all__ = ["TUTOR_PROMPT", "as_json", "render_markdown"]

#: What turns a model into a tutor rather than an answer key. The fourth rule is
#: the one that matters and the one a solver will test: it has to hold when they
#: ask outright.
TUTOR_PROMPT: Final = """\
You are a tutor helping me through a hands-on practice exercise. Everything \
below was generated by the practice tool I am using: the task, each command I \
ran and what it printed, any hints I chose to reveal, and the state things are \
in right now.

How to help:

- I am here to learn to do this myself. Give me the next thing to look at or \
think about, not the command or the code that solves it.
- Before you explain why something happened, ask me what I expected it to do.
- Work from what is recorded below. If you need to see something that is not \
there, tell me what to run and I will paste the result.
- Do not give me the full solution, even if I ask for it. If I am stuck, make \
the nudge more specific instead.
- If a verdict is included, the attempt is over: switch to a post-mortem. \
Explain each check I failed in terms of what I actually did, and what a \
different approach would have cost."""

_BACKTICK_RUN: Final = re.compile(r"`+")

#: The shortest fence Markdown allows, and the one used whenever the contents
#: hold nothing longer.
_MIN_FENCE: Final = 3


def render_markdown(context: TutorContext) -> str:
    """The whole bundle, prompt first, ready to paste into a chat."""
    sections = [
        TUTOR_PROMPT,
        "---",
        _summary(context),
        _section("The task", _fenced(context.prompt, "text")),
        _section("What I have done so far", _history(context)),
    ]
    if context.repo is not None:
        sections.append(_section("The repository right now", _repo(context.repo)))
    elif context.kind is ExerciseKind.GIT_SCENARIO:
        sections.append(
            _section(
                "The repository right now",
                "The repository is no longer on disk, so the history above is "
                "all there is to go on.",
            )
        )
    if context.source is not None:
        sections.append(
            _section(
                "My solution as it stands",
                _fenced(context.source, context.language or ""),
            )
        )
    if context.verdict is not None:
        sections.append(_section("The verdict", _verdict(context.verdict)))
    if context.notes is not None:
        sections.append(_section("The author's notes", context.notes.strip()))
    return "\n\n".join(sections) + "\n"


def as_json(context: TutorContext) -> dict[str, object]:
    """The same bundle as plain data, for `json.dumps`.

    Built from JSON's own types and nothing else -- no enum, no `Sha`, no
    frozenset -- so the caller serialises it without a `default=` hook that
    would have to know this module's vocabulary. Every collection is ordered,
    because a diff of two exports is one of the things a script does with them.
    """
    repo = context.repo
    verdict = context.verdict
    return {
        "tutor_prompt": TUTOR_PROMPT,
        "exercise": {
            "id": str(context.exercise_id),
            "title": context.title,
            "kind": context.kind.value,
            "difficulty": context.difficulty.value,
            "prompt": context.prompt,
        },
        "attempt": {
            "status": context.status.value,
            "mode": context.mode.value,
            "allowed_commands": list(context.allowed_commands),
            "commands_left": context.commands_left,
            "hints_left": context.hints_left,
        },
        "events": [_event_json(event) for event in context.events],
        "repository": _repo_json(repo) if repo is not None else None,
        "source": (
            {"language": context.language, "text": context.source}
            if context.source is not None
            else None
        ),
        "verdict": _verdict_json(verdict) if verdict is not None else None,
        "notes": context.notes,
    }


# --- markdown --------------------------------------------------------------


def _section(title: str, body: str) -> str:
    return f"## {title}\n\n{body}"


def _fenced(text: str, language: str = "") -> str:
    """`text` in a code fence it cannot close early. See the module docstring."""
    longest = max((len(run) for run in _BACKTICK_RUN.findall(text)), default=0)
    fence = "`" * max(_MIN_FENCE, longest + 1)
    return f"{fence}{language}\n{text.rstrip()}\n{fence}"


def _summary(context: TutorContext) -> str:
    """The title and the handful of facts that frame everything under it."""
    commands = [event for event in context.events if isinstance(event, CommandRun)]
    hints = len(context.events) - len(commands)
    kind = context.kind.value.replace("_", " ")
    lines = [
        f"# {context.title}",
        "",
        f"- Exercise: `{context.exercise_id}` ({kind}, {context.difficulty.value})",
        f"- Attempt: {context.status.value}, {context.mode.value} mode",
    ]
    # Only where there is a console. A kata's "0 commands run, 0 left" is true
    # and reads as a budget that has been spent.
    if context.allowed_commands:
        allowed = ", ".join(f"`{name}`" for name in context.allowed_commands)
        lines.append(
            f"- Commands: {len(commands)} run, {context.commands_left} left. "
            f"Allowed: {allowed}"
        )
    lines.append(f"- Hints: {hints} revealed, {context.hints_left} not yet revealed")
    return "\n".join(lines)


def _history(context: TutorContext) -> str:
    """Every command and every hint, in the order they happened.

    One numbered sequence rather than two lists, because the order between them
    is the evidence: a hint revealed *before* the command that fixed things and
    one revealed after it are different stories about the same attempt.
    """
    if not context.events:
        return "Nothing yet."
    return "\n\n".join(
        _command(number, event)
        if isinstance(event, CommandRun)
        else _hint(number, event)
        for number, event in enumerate(context.events, start=1)
    )


def _command(number: int, run: CommandRun) -> str:
    result = run.result
    parts = [f"**{number}.** Ran `{run.command_line}` (exit {result.exit_code})"]
    for name, text in (("stdout", result.stdout), ("stderr", result.stderr)):
        if text.strip():
            parts.append(f"{name}:\n\n{_fenced(text, 'text')}")
    if len(parts) == 1:
        parts.append("It printed nothing.")
    if result.truncated:
        parts.append("The tool cut this output short; there was more.")
    return "\n\n".join(parts)


def _hint(number: int, revealed: HintRevealed) -> str:
    return f"**{number}.** Revealed hint {revealed.index + 1}: {revealed.hint.text}"


def _repo(repo: RepoView) -> str:
    """The panel's reading of the repository, in the panel's order.

    Where you are, then the worktree, then the refs, then the stash, then the
    history -- the order `partials/repo-state.html` argues for, because it is
    the order someone reads a broken repository in.
    """
    lines = [
        f"- HEAD: {_head(repo)}",
        *_worktree(repo.status),
        _refs("Branches", repo.branches),
        _refs("Remote branches", repo.remote_branches),
        _refs("Tags", repo.tags),
        f"- Stash: {'; '.join(repo.stashes) or 'empty'}",
        "",
        "History, newest first, including commits no longer reachable from HEAD:",
        "",
    ]
    lines.extend(_commit(row, repo.head_sha) for row in repo.graph.rows)
    if repo.graph.is_empty:
        lines.append("- no commits")
    return "\n".join(lines)


def _head(repo: RepoView) -> str:
    sha = repo.head_sha
    if sha is None:
        return f"`{repo.head_branch or 'HEAD'}`, unborn (no commit on it yet)"
    if repo.is_detached:
        return f"detached at `{sha.short}`"
    return f"`{repo.head_branch}` at `{sha.short}`"


def _worktree(status: WorktreeStatus) -> list[str]:
    """The four states apart, because they are four problems with four fixes."""
    groups = (
        ("unmerged", status.unmerged),
        ("staged", status.staged),
        ("modified, not staged", status.unstaged),
        ("untracked", status.untracked),
    )
    lines = [
        f"- Worktree, {name}: {', '.join(f'`{path}`' for path in sorted(paths))}"
        for name, paths in groups
        if paths
    ]
    return lines or ["- Worktree: clean"]


def _refs(title: str, refs: Mapping[str, Sha]) -> str:
    listed = ", ".join(
        f"`{short_ref(name)}` at `{sha.short}`" for name, sha in refs.items()
    )
    return f"- {title}: {listed or 'none'}"


def _commit(row: GraphRow, head: Sha | None) -> str:
    """One commit, what points at it, and what it was built on.

    The parents are written out on every row rather than left to the order,
    because this is a list and not a drawing: two branches interleaved in one
    newest-first column are indistinguishable without them, and which commit
    sits on which is usually the question.
    """
    commit = row.commit
    labels = [short_ref(name) for name in row.refs]
    if commit.sha == head:
        labels.insert(0, "HEAD")
    pointed = f" ({', '.join(labels)})" if labels else ""
    parents = ", ".join(parent.short for parent in commit.parents) or "none"
    return f"- `{commit.sha.short}`{pointed} {commit.subject} [parents: {parents}]"


def _verdict(verdict: Verdict) -> str:
    passed = sum(report.passed for report in verdict.reports)
    outcome = verdict.outcome.value.replace("_", " ")
    lines = [
        f"Outcome: {outcome} ({passed} of {len(verdict.reports)} checks passed)",
        "",
    ]
    lines.extend(_report(report) for report in verdict.reports)
    return "\n".join(lines)


def _report(report: CheckReport) -> str:
    """One check as the verdict page shows it, and no more than it shows.

    A passing check is its label alone. The explanation is printed for a check
    that was *not* met, which is the page's rule (`partials/verdict.html`) and
    the right one here for a second reason: an explanation says why the check
    exists, and for one that passed the solver has not been told.
    """
    if report.passed:
        return f"- Passed: {report.label}"
    state = "Failed" if report.is_required else "Advisory, not met"
    line = f"- {state}: {report.label}"
    if report.expected and report.actual:
        line += f" Expected {report.expected}, got {report.actual}."
    if report.explanation:
        line += f" {report.explanation.strip()}"
    return line


# --- json ------------------------------------------------------------------


def _event_json(event: CommandRun | HintRevealed) -> dict[str, object]:
    if isinstance(event, CommandRun):
        return {
            "type": "command",
            "command": event.command_line,
            "exit_code": event.result.exit_code,
            "stdout": event.result.stdout,
            "stderr": event.result.stderr,
            "truncated": event.result.truncated,
        }
    return {"type": "hint", "number": event.index + 1, "text": event.hint.text}


def _repo_json(repo: RepoView) -> dict[str, object]:
    sha = repo.head_sha
    return {
        "head": {
            "branch": repo.head_branch,
            "sha": sha.value if sha is not None else None,
            "detached": repo.is_detached,
        },
        "worktree": {
            "unmerged": sorted(repo.status.unmerged),
            "staged": sorted(repo.status.staged),
            "unstaged": sorted(repo.status.unstaged),
            "untracked": sorted(repo.status.untracked),
        },
        "branches": _refs_json(repo.branches),
        "remote_branches": _refs_json(repo.remote_branches),
        "tags": _refs_json(repo.tags),
        "stashes": list(repo.stashes),
        "history": [
            {
                "sha": row.commit.sha.value,
                "subject": row.commit.subject,
                "parents": [parent.value for parent in row.commit.parents],
                "refs": [short_ref(name) for name in row.refs],
            }
            for row in repo.graph.rows
        ],
    }


def _refs_json(refs: Mapping[str, Sha]) -> dict[str, str]:
    return {short_ref(name): sha.value for name, sha in refs.items()}


def _verdict_json(verdict: Verdict) -> dict[str, object]:
    return {
        "outcome": verdict.outcome.value,
        "checks": [
            {
                "label": report.label,
                "severity": report.severity.value,
                "passed": report.passed,
                "expected": None if report.passed else report.expected,
                "actual": None if report.passed else report.actual,
                "explanation": None if report.passed else report.explanation,
            }
            for report in verdict.reports
        ],
    }
